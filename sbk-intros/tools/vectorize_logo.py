# Vectorizes the SBK "S + mic" mark into separate, animatable SVG shapes.
# Output: src/logoPaths.ts (coordinates are in the original 1254px logo space).
import numpy as np, potrace
from PIL import Image, ImageDraw

SCALE = 3
im = Image.open("public/mark.jpg").convert("RGB")
a = np.asarray(im).astype(np.float32)[..., 0] / 252.0
a = np.clip(a, 0, 1)

# Bars: orange pixels with 505<=x<=700 and y in the two bar bands (nothing else lives there)
BAR_Y = [(540, 688)]
bars_mask = np.zeros_like(a, dtype=bool)
bars_mask[540:688, 505:700] = True
body = a.copy(); body[bars_mask] = 0           # S halves WITHOUT the grille bars

big = Image.fromarray((body * 255).astype(np.uint8)).resize((a.shape[1] * SCALE, a.shape[0] * SCALE), Image.BICUBIC)
bm = np.asarray(big) > 127

def curve_to_d(c, s=1.0 / SCALE):
    f = lambda p: f"{p.x * s:.2f},{p.y * s:.2f}"
    d = f"M{f(c.start_point)}"
    for seg in c.segments:
        if seg.is_corner:
            d += f"L{f(seg.c)}L{f(seg.end_point)}"
        else:
            d += f"C{f(seg.c1)} {f(seg.c2)} {f(seg.end_point)}"
    return d + "Z"

def sample(c, s=1.0 / SCALE, n=14):
    pts = [(c.start_point.x * s, c.start_point.y * s)]; p0 = c.start_point
    for seg in c.segments:
        if seg.is_corner:
            pts += [(seg.c.x * s, seg.c.y * s), (seg.end_point.x * s, seg.end_point.y * s)]
        else:
            for i in range(1, n + 1):
                t = i / n
                x = (1-t)**3*p0.x + 3*(1-t)**2*t*seg.c1.x + 3*(1-t)*t*t*seg.c2.x + t**3*seg.end_point.x
                y = (1-t)**3*p0.y + 3*(1-t)**2*t*seg.c1.y + 3*(1-t)*t*t*seg.c2.y + t**3*seg.end_point.y
                pts.append((x * s, y * s))
        p0 = seg.end_point
    return pts

plist = potrace.Bitmap(bm).trace(turdsize=200, alphamax=1.0, opticurve=True, opttolerance=0.35)
curves = list(plist)
print("curves:", len(curves))
pieces = []
for c in curves:
    pts = np.array(sample(c))
    pieces.append((pts[:, 1].mean(), curve_to_d(c), pts))
pieces = [p for p in pieces if p[2][:,0].max() - p[2][:,0].min() < 1200]   # drop any frame-border artefact
pieces.sort(key=lambda p: p[0])
assert len(pieces) == 2, len(pieces)
top, bottom = pieces[0], pieces[1]

# ---- verify: rasterize traced shapes + bars, compare with source (IoU)
W, H = a.shape[1], a.shape[0]
chk = Image.new("L", (W * 2, H * 2), 0); dr = ImageDraw.Draw(chk)
for p in (top, bottom): dr.polygon([(x * 2, y * 2) for x, y in p[2]], fill=255)
dr.rounded_rectangle((504 * 2, 544 * 2, 677 * 2, 592 * 2), radius=24 * 2, fill=255)
dr.rounded_rectangle((504 * 2, 633 * 2, 677 * 2, 683 * 2), radius=25 * 2, fill=255)
chk = np.asarray(chk.resize((W, H), Image.LANCZOS)) > 127
src = a > 0.5
print("IoU", (chk & src).sum() / (chk | src).sum())

ts = f"""// AUTO-GENERATED by tools/vectorize_logo.py - SBK mark, original 1254px logo space.
export const LOGO_VIEWBOX = {{x: 168, y: 205, w: 952, h: 874}};
export const TOP_D = "{top[1]}";
export const BOTTOM_D = "{bottom[1]}";
export const BAR1_D = "M504,544H653A24,24 0 0 1 653,592H504Z";
export const BAR2_D = "M504,633H652A25,25 0 0 1 652,683H504Z";
export const CAPSULE = {{x: 505, y: 364, w: 272, h: 559, r: 136}};
export const MARK_CENTER = {{x: 644, y: 642}};
"""
open("src/logoPaths.ts", "w").write(ts)
print("written", len(ts), "bytes")
